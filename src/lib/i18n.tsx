type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: string) => string;
  fullName: string;
};

const I18nContext = createContext<Ctx | null>(null);

const STORAGE_KEY = "agrisynapse-lang";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY) as Lang | null;
      if (saved && ["en", "hi", "pa", "ta", "te", "mr"].includes(saved)) {
        setLangState(saved);
      }
    } catch {
      /* ignore */
    }
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* ignore */
    }
  };

  const t = (k: string) => {
    return STRINGS[lang]?.[k] ?? STRINGS.en?.[k] ?? k;
  };

  const fullName = LANGUAGES.find((l) => l.code === lang)?.full ?? "English";

  return (
    <I18nContext.Provider value={{ lang, setLang, t, fullName }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}