type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: keyof typeof STRINGS["en"]) => string;
  fullName: string;
};

const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>("en");
  const t = (k: keyof typeof STRINGS["en"]) =>
    STRINGS[lang][k] ?? STRINGS.en[k] ?? String(k);
  const fullName = LANGUAGES.find((l) => l.code === lang)?.full ?? "English";
  return (
    <I18nContext.Provider value={{ lang, setLang, t, fullName }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}